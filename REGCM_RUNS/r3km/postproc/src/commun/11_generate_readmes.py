def generate_standard_readme(folder_name, files):
    return f"""# {folder_name.capitalize()} Results

**Directory**: `postproc/results/{folder_name}`

## Current Contents
{chr(10).join([f"- `{f}`" for f in sorted(files) if not f.endswith('README.md')]) if files else "*No figures generated yet.*"}

---
*Note: This README is automatically generated and updated via `src/commun/11_generate_readmes.py`.*
"""

def main():
    if not RESULTS_DIR.exists():
        RESULTS_DIR.mkdir(parents=True, exist_ok=True)
        
    def process_directory(d, folder_type):
        files = []
        for root, _, filenames in os.walk(d):
            for filename in filenames:
                if filename.startswith('.') or filename.lower() == 'readme.md':
                    continue
                rel_path = os.path.relpath(os.path.join(root, filename), d)
                files.append(rel_path)
                
        if folder_type == "maps":
            content = generate_maps_readme(files)
        elif folder_type == "pdfs":
            content = generate_pdfs_readme(files)
        elif folder_type == "domain":
            content = generate_domain_readme(files)
        else:
            content = generate_standard_readme(folder_type, files)
            
        readme_path = d / "README.md"
        with open(readme_path, "w") as f:
            f.write(content)
        print(f"Generated {readme_path}")

    # Process domain and period folders
    for item in RESULTS_DIR.iterdir():
        if not item.is_dir():
            continue
        
        if item.name == "domain":
            process_directory(item, "domain")
        elif "_to_" in item.name:
            # It's a period folder
            for sub in item.iterdir():
                if sub.is_dir():
                    process_directory(sub, sub.name)
        else:
            process_directory(item, item.name)

if __name__ == "__main__":
    main()
