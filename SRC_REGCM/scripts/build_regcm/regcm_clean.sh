#!/bin/bash
# ---------------------------------------------------------------------------
# Author: M. El Aabaribaoune (@um6p)
# Description:
# This script cleans up the previous compilation of RegCM by running
# 'make clean' and 'make distclean' in the specified RegCM directory.
# It also removes specific configuration files and clears the contents of the 'bin' directory if it exists.
# ---------------------------------------------------------------------------

# Check if the user provided a directory as an argument
if [ "$#" -ne 1 ]; then
    echo "Please provide the path to your RegCM project to clean as an argument to this script!"
    exit 1
fi

# Assign the first argument to PROJECT_DIR
PROJECT_DIR="$1"

echo "=== Cleaning previous compilation in $PROJECT_DIR ==="

# Change to the project directory
cd "$PROJECT_DIR" || { echo "Failed to change directory to $PROJECT_DIR. Exiting."; exit 1; }

# Clean up files generated during compilation
echo "Running 'make clean'..."
make clean | tee make_clean_output.txt
if [ $? -ne 0 ]; then
    echo "Error during cleanup with 'make clean'."
else
    echo "'make clean' completed successfully. Deleted files logged in make_clean_output.txt."
fi

# Clean up all files generated by the configuration process
echo "Running 'make distclean'..."
make distclean | tee make_distclean_output.txt
if [ $? -ne 0 ]; then
    echo "Error during cleanup with 'make distclean'."
else
    echo "'make distclean' completed successfully. Deleted files logged in make_distclean_output.txt."
fi

# Remove specific configuration files, if present
CONFIG_FILES=("config.log" "config.status")
echo "Removing configuration files if they exist..."

for file in "${CONFIG_FILES[@]}"; do
    if [ -f "$file" ]; then
        echo "Deleting: $file"
        rm -f "$file"
        if [ $? -eq 0 ]; then
            echo "$file deleted successfully."
        else
            echo "Error deleting $file."
        fi
    else
        echo "$file not found, skipping."
    fi
done

# Clear the contents of the 'bin' directory if it exists
if [ -d "bin" ]; then
    echo "Clearing contents of 'bin' directory..."
    rm -rf "bin/*"
    if [ $? -eq 0 ]; then
        echo "Contents of 'bin' directory cleared successfully."
    else
        echo "Error clearing contents of 'bin' directory."
    fi
else
    echo "'bin' directory not found, skipping."
fi

# Print project directory
echo "=== Cleanup completed ==="
echo "RegCM directory: $PROJECT_DIR"

